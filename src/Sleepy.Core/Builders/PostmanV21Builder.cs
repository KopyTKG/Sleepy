using System.Security.Cryptography;
using System.Text;
using System.Text.Json.Nodes;
using Sleepy.OpenApi;
using Sleepy.Serialization;

namespace Sleepy.Builders;

/// <summary>
/// A Postman collection (schema v2.1): one JSON document whose <c>item</c> array
/// nests folders and requests.
///
/// Postman differs from Insomnia in three ways that matter here: variables are
/// written <c>{{baseUrl}}</c> rather than <c>{{ _.baseUrl }}</c>, a URL is an
/// object rather than a string, and path parameters are <c>:id</c> segments with
/// a matching <c>variable</c> entry rather than the <c>{id}</c> the spec uses.
/// </summary>
public sealed class PostmanV21Builder : ICollectionBuilder
{
    private const string Schema = "https://schema.getpostman.com/json/collection/v2.1.0/collection.json";

    public string FormatId => "postman";

    public string DisplayName => "Postman v2.1";

    public string DefaultOutputName => "postman-collection.json";

    public bool IsFolderFormat => false;

    public BuiltCollection Build(IReadOnlyList<ApiModule> modules, BuildOptions options)
        => BuiltCollection.Single(FormatId, DefaultOutputName, JsonWriter.Write(BuildDocument(modules, options)));

    /// <summary>Exposed for tests; the collection as a JSON tree.</summary>
    public static JsonNode BuildDocument(IReadOnlyList<ApiModule> modules, BuildOptions options)
    {
        var name = CollectionPlan.ResolveName(modules, options.WorkspaceName);
        var baseUrlVariables = CollectionPlan.ResolveBaseUrlVariables(modules);
        var multiModule = modules.Count > 1;

        var items = new JsonArray();
        for (var index = 0; index < modules.Count; index++)
        {
            var module = modules[index];
            if (!CollectionPlan.Contributes(module, modules.Count))
            {
                continue;
            }

            var operations = Operations.Collect(module.Spec);
            var variable = baseUrlVariables[index];

            foreach (var item in BuildModuleItems(module, operations, variable, options.Layout, multiModule))
            {
                items.Add(item);
            }
        }

        var variables = new JsonArray();
        foreach (var entry in CollectionPlan.ResolveVariables(modules, baseUrlVariables, options.BearerToken))
        {
            JsonNode declaration = new JsonObject
            {
                ["key"] = entry.Key,
                ["value"] = entry.Value,
                ["type"] = "string",
            };
            variables.Add(declaration);
        }

        JsonNode bearer = new JsonObject
        {
            ["key"] = "token",
            ["value"] = "{{" + CollectionPlan.BearerVariable + "}}",
            ["type"] = "string",
        };

        return new JsonObject
        {
            ["info"] = new JsonObject
            {
                ["_postman_id"] = StableId(name),
                ["name"] = name,
                ["description"] = $"Generated by sleepy from {options.SourceName}",
                ["schema"] = Schema,
            },
            ["auth"] = new JsonObject
            {
                ["type"] = "bearer",
                ["bearer"] = BearerAuth(bearer),
            },
            ["variable"] = variables,
            ["item"] = items,
        };
    }

    private static JsonArray BearerAuth(JsonNode entry)
    {
        var auth = new JsonArray();
        auth.Add(entry);
        return auth;
    }

    /// <summary>The items one module contributes, arranged by the chosen layout.</summary>
    private static IEnumerable<JsonNode> BuildModuleItems(
        ApiModule module,
        List<Operation> operations,
        string baseUrlVariable,
        FolderLayout layout,
        bool multiModule)
    {
        var requests = operations
            .Select(operation => (JsonNode)BuildRequest(operation, baseUrlVariable, module.Spec))
            .ToList();

        if (layout == FolderLayout.ModuleOnly || !AnyTags(operations))
        {
            yield return multiModule ? Folder(module.Name, requests) : Requests(requests);
            yield break;
        }

        var tags = operations.Select(operation => operation.Tag).Distinct().ToList();
        tags.Sort(StringComparer.Ordinal);

        var folders = tags
            .Select(tag => (JsonNode)Folder(
                multiModule && layout == FolderLayout.Flat ? $"{module.Name} / {tag}" : tag,
                operations
                    .Where(operation => operation.Tag == tag)
                    .Select(operation => (JsonNode)BuildRequest(operation, baseUrlVariable, module.Spec))
                    .ToList()))
            .ToList();

        if (multiModule && layout == FolderLayout.Nested)
        {
            yield return Folder(module.Name, folders);
            yield break;
        }

        foreach (var folder in folders)
        {
            yield return folder;
        }
    }

    private static bool AnyTags(List<Operation> operations)
        => operations.Any(operation => operation.Tag != Operations.DefaultTag);

    private static JsonObject Folder(string name, IReadOnlyList<JsonNode> children)
    {
        var items = new JsonArray();
        foreach (var child in children)
        {
            items.Add(child.DeepClone());
        }

        return new JsonObject
        {
            ["name"] = name,
            ["item"] = items,
        };
    }

    /// <summary>A layout with nothing to nest still needs a single item wrapper.</summary>
    private static JsonObject Requests(IReadOnlyList<JsonNode> children)
        => Folder(Operations.DefaultTag, children);

    private static JsonObject BuildRequest(Operation operation, string baseUrlVariable, JsonNode? spec)
    {
        var request = new JsonObject
        {
            ["method"] = operation.Method.ToUpperInvariant(),
            ["header"] = BuildHeaders(operation),
            ["url"] = BuildUrl(operation, baseUrlVariable),
        };

        if (operation.Summary.Length > 0)
        {
            request["description"] = operation.Summary;
        }

        if (RequestBody(operation, spec) is { } body)
        {
            request["body"] = body;
        }

        return new JsonObject
        {
            ["name"] = $"{operation.Method.ToUpperInvariant()} {operation.Path}",
            ["request"] = request,
            ["response"] = new JsonArray(),
        };
    }

    private static JsonArray BuildHeaders(Operation operation)
    {
        var headers = new JsonArray();
        if (Json.Get(operation.Node, "requestBody") is not null)
        {
            JsonNode contentType = new JsonObject
            {
                ["key"] = "Content-Type",
                ["value"] = "application/json",
                ["type"] = "text",
            };
            headers.Add(contentType);
        }

        return headers;
    }

    private static JsonObject BuildUrl(Operation operation, string baseUrlVariable)
    {
        var hostVariable = "{{" + baseUrlVariable + "}}";
        var segments = operation.Path
            .Split('/', StringSplitOptions.RemoveEmptyEntries)
            .Select(ToPostmanSegment)
            .ToList();

        var path = new JsonArray();
        foreach (var segment in segments)
        {
            path.Add((JsonNode)JsonValue.Create(segment));
        }

        var host = new JsonArray();
        host.Add((JsonNode)JsonValue.Create(hostVariable));

        var url = new JsonObject
        {
            ["raw"] = hostVariable + "/" + string.Join('/', segments),
            ["host"] = host,
            ["path"] = path,
        };

        if (BuildQuery(operation) is { Count: > 0 } query)
        {
            url["query"] = query;
        }

        if (BuildPathVariables(operation.Path) is { Count: > 0 } variables)
        {
            url["variable"] = variables;
        }

        return url;
    }

    /// <summary>OpenAPI writes <c>{id}</c>; Postman writes <c>:id</c>.</summary>
    private static string ToPostmanSegment(string segment)
        => segment.StartsWith('{') && segment.EndsWith('}')
            ? ":" + segment[1..^1]
            : segment;

    private static JsonArray BuildPathVariables(string path)
    {
        var variables = new JsonArray();
        foreach (var segment in path.Split('/', StringSplitOptions.RemoveEmptyEntries))
        {
            if (segment.StartsWith('{') && segment.EndsWith('}'))
            {
                JsonNode variable = new JsonObject
                {
                    ["key"] = segment[1..^1],
                    ["value"] = string.Empty,
                };
                variables.Add(variable);
            }
        }

        return variables;
    }

    private static JsonArray BuildQuery(Operation operation)
    {
        var query = new JsonArray();
        if (Json.AsArray(Json.Get(operation.Node, "parameters")) is not { } parameters)
        {
            return query;
        }

        foreach (var parameter in parameters)
        {
            if (Json.GetString(parameter, "in") != "query")
            {
                continue;
            }

            JsonNode entry = new JsonObject
            {
                ["key"] = Json.GetString(parameter, "name") ?? string.Empty,
                ["value"] = string.Empty,
                ["disabled"] = false,
                ["description"] = Json.GetString(parameter, "description") ?? string.Empty,
            };
            query.Add(entry);
        }

        return query;
    }

    private static JsonObject? RequestBody(Operation operation, JsonNode? spec)
    {
        var schema = Json.Get(
            Json.Get(Json.Get(Json.Get(operation.Node, "requestBody"), "content"), "application/json"),
            "schema");

        if (schema is null)
        {
            return null;
        }

        return new JsonObject
        {
            ["mode"] = "raw",
            ["raw"] = JsonWriter.Write(ExampleGenerator.Generate(schema, spec)),
            ["options"] = new JsonObject
            {
                ["raw"] = new JsonObject { ["language"] = "json" },
            },
        };
    }

    /// <summary>
    /// Postman expects a UUID here. Deriving it from the collection name keeps
    /// re-runs byte-identical, which a random one would not.
    /// </summary>
    private static string StableId(string name)
    {
        var hash = SHA256.HashData(Encoding.UTF8.GetBytes("sleepy:" + name));
        return new Guid(hash.AsSpan(0, 16)).ToString();
    }
}
